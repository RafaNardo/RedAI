public sealed class OpenAIResponsesClient(HttpClient http, IConfiguration configuration, IAIRunWriter? runs = null) : IAIClient
{
    public string Mode => "openai";

    public async Task<T> CompleteAsync<T>(string operation, object input, CancellationToken cancellationToken = default)
    {
        using var schema = JsonDocument.Parse("{\"type\":\"object\",\"additionalProperties\":true}");
        using var output = await CompleteStructuredAsync(new StructuredTextRequest(operation, "Return valid JSON.", input, "red_ai_generic", schema), cancellationToken);
        return output.Deserialize<T>() ?? throw new InvalidOperationException("OpenAI returned an empty structured output.");
    }

    public async Task<JsonDocument> CompleteStructuredAsync(StructuredTextRequest request, CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(request.Operation); ArgumentException.ThrowIfNullOrWhiteSpace(request.SchemaName);
        var model = request.Model ?? Required("AI:Models:Reasoning");
        var runId = await StartRunAsync(request.Operation, model, request.Input, cancellationToken);
        using var message = Authorized(HttpMethod.Post, "https://api.openai.com/v1/responses");
        // Responses uses text.format/json_schema for strict Structured Outputs.
        message.Content = JsonContent.Create(new {
            model, store = false, instructions = request.Instructions,
            input = JsonSerializer.Serialize(request.Input),
            text = new { format = new { type = "json_schema", name = request.SchemaName, strict = true, schema = JsonNode.Parse(request.Schema.RootElement.GetRawText()) } }
        });
        try { using var response = await http.SendAsync(message, cancellationToken); response.EnsureSuccessStatusCode(); using var body = JsonDocument.Parse(await response.Content.ReadAsStringAsync(cancellationToken)); var json = ExtractOutputText(body.RootElement); await CompleteRunAsync(runId, json, cancellationToken); return JsonDocument.Parse(json); }
        catch (Exception ex) { await FailRunAsync(runId, ex, cancellationToken); throw; }
    }

    public async Task<GeneratedImage> GenerateImageAsync(ImageGenerationRequest request, CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(request.Prompt);
        var model = request.Model ?? Required("AI:Models:Image");
        var runId = await StartRunAsync(request.Operation, model, new { request.Prompt, request.Size, request.Quality, request.OutputFormat }, cancellationToken);
        using var message = Authorized(HttpMethod.Post, "https://api.openai.com/v1/images/generations");
        message.Content = JsonContent.Create(new { model, prompt = request.Prompt, size = request.Size, quality = request.Quality, output_format = request.OutputFormat, n = 1 });
        try { using var response = await http.SendAsync(message, cancellationToken); response.EnsureSuccessStatusCode(); using var body = JsonDocument.Parse(await response.Content.ReadAsStringAsync(cancellationToken)); var encoded = body.RootElement.GetProperty("data")[0].GetProperty("b64_json").GetString() ?? throw new InvalidOperationException("OpenAI image response did not contain b64_json."); var type = request.OutputFormat.Equals("jpeg", StringComparison.OrdinalIgnoreCase) ? "image/jpeg" : "image/png"; await CompleteRunAsync(runId, "{\"asset\":\"stored-by-caller\"}", cancellationToken); return new GeneratedImage(Convert.FromBase64String(encoded), type, model); }
        catch (Exception ex) { await FailRunAsync(runId, ex, cancellationToken); throw; }
    }

    private HttpRequestMessage Authorized(HttpMethod method, string uri)
    {
        var message = new HttpRequestMessage(method, uri);
        message.Headers.Authorization = new AuthenticationHeaderValue("Bearer", Required("ai-api-key"));
        return message;
    }
    private string Required(string key) => configuration[key] ?? throw new InvalidOperationException($"Server-side configuration '{key}' is required when AI_MODE=openai.");
    private async Task<Guid?> StartRunAsync(string operation, string model, object input, CancellationToken ct)
    {
        if (runs is null) return null;
        var sanitized = JsonSerializer.Serialize(input).Replace("ai-api-key", "[redacted]", StringComparison.OrdinalIgnoreCase);
        return await runs.StartAsync(new AIRunStart(operation, "ai", Guid.Empty, model, sanitized), ct);
    }
    private Task CompleteRunAsync(Guid? id, string output, CancellationToken ct) => id is { } value && runs is not null ? runs.CompleteAsync(value, output, ct) : Task.CompletedTask;
    private Task FailRunAsync(Guid? id, Exception error, CancellationToken ct) => id is { } value && runs is not null ? runs.FailAsync(value, error.Message, ct) : Task.CompletedTask;
    private static string ExtractOutputText(JsonElement root) => root.GetProperty("output").EnumerateArray()
        .SelectMany(item => item.TryGetProperty("content", out var content) ? content.EnumerateArray() : [])
        .FirstOrDefault(item => item.TryGetProperty("type", out var type) && type.GetString() == "output_text")
        .GetProperty("text").GetString() ?? throw new InvalidOperationException("OpenAI response did not contain output_text.");
}
