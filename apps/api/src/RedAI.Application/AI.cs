using Microsoft.Extensions.Configuration;
using System.Net.Http.Headers;
using System.Net.Http.Json;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace RedAI.Application;

/// <summary>All live model calls are server-side. Machine-readable stages must use CompleteStructuredAsync.</summary>
public interface IAIClient
{
    string Mode { get; }
    Task<T> CompleteAsync<T>(string operation, object input, CancellationToken cancellationToken = default);
    Task<JsonDocument> CompleteStructuredAsync(StructuredTextRequest request, CancellationToken cancellationToken = default);
    Task<GeneratedImage> GenerateImageAsync(ImageGenerationRequest request, CancellationToken cancellationToken = default);
}

public sealed record StructuredTextRequest(string Operation, string Instructions, object Input, string SchemaName, JsonDocument Schema, string? Model = null);
public sealed record ImageGenerationRequest(string Operation, string Prompt, string Size = "1024x1536", string Quality = "medium", string OutputFormat = "png", string? Model = null);
public sealed record GeneratedImage(byte[] Bytes, string ContentType, string Model);
public sealed record StoredGeneratedImage(StoredAsset Asset, string Model);
public sealed record AIRunStart(string Operation, string EntityType, Guid EntityId, string Model, string InputJson);
public interface IAIRunWriter { Task<Guid> StartAsync(AIRunStart run, CancellationToken ct); Task CompleteAsync(Guid id, string outputJson, CancellationToken ct); Task FailAsync(Guid id, string error, CancellationToken ct); }

public interface IContractSchemaCatalog { JsonDocument Load(string schemaName); }

/// <summary>Loads the frozen schemas in docs/contracts. The root is explicitly configured by the host.</summary>
public sealed class FileContractSchemaCatalog(string contractsRoot) : IContractSchemaCatalog
{
    public JsonDocument Load(string schemaName)
    {
        if (string.IsNullOrWhiteSpace(schemaName) || schemaName.IndexOfAny(Path.GetInvalidFileNameChars()) >= 0 || schemaName.Contains("..", StringComparison.Ordinal))
            throw new ArgumentException("Invalid contract schema name.", nameof(schemaName));
        var path = Path.Combine(contractsRoot, schemaName.EndsWith(".schema.json", StringComparison.Ordinal) ? schemaName : $"{schemaName}.schema.json");
        if (!File.Exists(path)) throw new FileNotFoundException($"RED AI contract schema was not found: {schemaName}", path);
        return JsonDocument.Parse(File.ReadAllText(path));
    }
}

/// <summary>Application service that stores generated image bytes under a domain storage key.</summary>
public sealed class VisualAssetGenerator(IAIClient client, IAssetStorage storage)
{
    public async Task<StoredGeneratedImage> GenerateAndStoreAsync(ImageGenerationRequest request, string storageKey, CancellationToken ct = default)
    {
        var generated = await client.GenerateImageAsync(request, ct);
        await using var bytes = new MemoryStream(generated.Bytes, writable: false);
        return new StoredGeneratedImage(await storage.PutAsync(bytes, storageKey, generated.ContentType, ct), generated.Model);
    }
}

